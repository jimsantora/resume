#!/usr/bin/env node
// Generates tui/src/content.rs from lib/resume.ts so the TUI and the website share one source of truth.
// Usage (from repo root): node scripts/gen-tui-content.cjs
// Needs the `typescript` package (a devDependency) to be resolvable.
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'lib/resume.ts'), 'utf8');
const js = ts.transpileModule(src, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText;
const mod = { exports: {} };
new Function('module', 'exports', js)(mod, mod.exports);
const R = mod.exports;

// Rust string literal. JSON escaping matches Rust for everything except \uXXXX, which JSON only uses
// for control characters; refuse those rather than mis-encode them.
const s = v => {
  const out = JSON.stringify(String(v));
  if (/\\u[0-9a-fA-F]{4}/.test(out)) throw new Error(`control character in: ${v}`);
  return out;
};
const arr = xs => `&[${xs.map(s).join(', ')}]`;
const slug = t => t.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const out = `// @generated by scripts/gen-tui-content.cjs from lib/resume.ts. Do not edit by hand.

pub struct Profile {
    pub name: &'static str,
    pub title: &'static str,
    pub discipline: &'static str,
    pub pitch: &'static str,
}

pub struct Job {
    pub title: &'static str,
    pub company: &'static str,
    pub period: &'static str,
    pub slug: &'static str,
    pub details: &'static [&'static str],
}

pub struct Credit {
    pub title: &'static str,
    pub year: &'static str,
    pub role: &'static str,
    pub slug: &'static str,
}

pub struct SkillGroup {
    pub id: &'static str,
    pub label: &'static str,
    pub items: &'static [&'static str],
}

pub const PROFILE: Profile = Profile {
    name: ${s(R.profile.name)},
    title: ${s(R.profile.title)},
    discipline: ${s(R.profile.discipline)},
    pitch: ${s(R.profile.pitch)},
};

pub const EMPLOYERS: &[&str] = ${arr(R.profile.employers)};
pub const GITHUB: &str = ${s(R.links.github.href)};
pub const LINKEDIN: &str = ${s(R.links.linkedin.href)};
pub const ABOUT: &[&str] = ${arr(R.about)};
pub const SPECIALTIES: &[&str] = ${arr(R.specialties)};

pub const JOBS: &[Job] = &[
${R.jobs.map(j => `    Job {
        title: ${s(j.title)},
        company: ${s(j.company)},
        period: ${s(j.period)},
        slug: ${s(R.jobSlug(j))},
        details: ${arr(j.details)},
    },`).join('\n')}
];

pub const CREDITS: &[Credit] = &[
${R.credits.map(c => `    Credit { title: ${s(R.displayTitle(c.title))}, year: ${s(c.year)}, role: ${s(c.role)}, slug: ${s(slug(c.title))} },`).join('\n')}
];

pub const SKILLS: &[SkillGroup] = &[
${R.skills.map(g => `    SkillGroup { id: ${s(g.dir)}, label: ${s(g.label)}, items: ${arr(g.items)} },`).join('\n')}
];
`;

fs.writeFileSync(path.join(root, 'tui/src/content.rs'), out);
console.log(`wrote tui/src/content.rs: ${R.jobs.length} jobs, ${R.credits.length} credits, ${R.skills.length} skill groups`);
